# frozen_string_literal: true

# Rubotty relays messages between chat platforms.
#
# Reading order for someone new: adapters/base.rb (the platform contract),
# core/room.rb (the N way topology), core/router.rb (fan out and loop
# prevention), and core/rich_text.rb (the canonical message).
module Rubotty
  autoload :VERSION, "rubotty/version"
end

# A container sets no locale, so Encoding.default_external comes out
# US-ASCII and every bare File.read inherits it invisibly. Set once here
# rather than annotated at each call site, since the failure is a call
# site somebody forgot, not one somebody wrote wrong.
Encoding.default_external = Encoding::UTF_8

